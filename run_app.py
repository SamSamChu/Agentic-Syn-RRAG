            test_500 = pd.read_csv(input_file) #500_samples_rag_agentic.csv")
            sample_inputs = []
            count = 0
            #read checkpoint file
            checkpoint_file = f"{prefix_checkpoint}_checkpoint.json"
            #start_idx = 56
