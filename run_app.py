def resolve_index_range(start_index, end_index, shard_id, num_shards, total_records):
    if (shard_id is None) != (num_shards is None):
        raise ValueError("--shard_id and --num_shards must be provided together")
    if shard_id is not None:
        if total_records is None:
            raise ValueError("--total_records is required when using --shard_id/--num_shards")
        if shard_id < 0 or shard_id >= num_shards:
            raise ValueError("--shard_id must be in [0, num_shards)")
        records_per_shard = (total_records + num_shards - 1) // num_shards
        start_index = shard_id * records_per_shard
        end_index = min(total_records, (shard_id + 1) * records_per_shard)
    return start_index, end_index


def _split_smiles_components(smiles_text):
    return [
        part.strip()
        for part in str(smiles_text or "").split(".")
        if part.strip()
    ]


def _entries_from_smiles(smiles_text, name_prefix, default_key):
    entries = []
    for idx, smiles in enumerate(_split_smiles_components(smiles_text), start=1):
        entry = {
            "name": f"{name_prefix}_{idx}",
            "smiles": smiles,
        }
        entry[default_key] = 1.0
        entries.append(entry)
    return entries


def _condition_field(condition, field):
    match = re.search(
        field + r"\s*:\s*(.*?)(?:\s+(?:reagents|solvents|catalysts|temperature|time)\s*:|$)",
        str(condition or ""),
        flags=re.I,
    )
    return match.group(1).strip() if match else ""


def _has_reaction_conditions(recipe):
    if not isinstance(recipe, dict):
        return False
    reaction_conditions = recipe.get("reaction_conditions")
    if not isinstance(reaction_conditions, dict):
        return False
    reactants = reaction_conditions.get("reactants")
    return isinstance(reactants, list) and len(reactants) > 0


def _fallback_recipe_from_local_pathway(pathway, product_smiles):
    pathway = pathway if isinstance(pathway, dict) else {}
    reactants = pathway.get("reactants", "")
    condition = pathway.get("condition", "")
    reagents = _condition_field(condition, "reagents")
    solvents = _condition_field(condition, "solvents")
    return {
        "reaction_name": "Local model fallback recipe",
        "recommendation_and_ranking": {
            "ranking": pathway.get("pathway_id"),
            "rationale": (
                "Agent recipe JSON was empty or invalid, so this recipe was "
                "constructed from the local model pathway to preserve evaluable "
                "reactants and conditions."
            ),
            "confidence_score": 1,
        },
        "reactant_revision": {
            "changed": False,
            "original_reactants": reactants,
            "final_reactants": reactants,
            "alternative_reactants": [],
            "policy_note": "Fallback generated by run_app.py because agent recipe was empty.",
        },
        "reaction_conditions": {
            "reactants": _entries_from_smiles(reactants, "local_reactant", "equivalents"),
            "reagents": _entries_from_smiles(reagents, "local_reagent", "equivalents"),
            "solvents": _entries_from_smiles(solvents, "local_solvent", "volume"),
            "temperature": None,
            "time": None,
        },
        "procedure": (
            "Fallback recipe generated from the local model prediction. "
            f"Target product: {product_smiles}."
        ),
    }


def _extract_recipe_from_report(report):
    pattern = r"```json\s*(\{.*?\})\s*```"
    match = re.search(pattern, str(report or ""), re.DOTALL)
    if not match:
        return None
    json_str = match.group(1).strip()
    try:
        return json.loads(json_str)
    except json.JSONDecodeError:
        try:
            return ast.literal_eval(json_str)
        except Exception:
            return None


