async def judge_with_litellm_self_correction(product_smiles, retrieval_rerank, full_recipe, sample, model_id=claude_sonnet_4_5):
    prompt_template = Template("""
    You are an Expert Chemical RAG Evaluator in Organic Synthesis. You must determine if an Agent's generated recipe is grounded in the retrieved reference reactions or if it is hallucinated/derived solely from internal training data.

    * **Inputs:**
        * Retrieved Contexts (List of 3): Top-3 similar reactions found in the database:
            ${retrieval_rerank}
        * Target Recipe: The recipe generated by the Agent:
            ${full_recipe}
        * Target product(s) SMILES:
            ${product_smiles}

    * **The "Grounding" Philosophy:**
        * The retrieved reactions are analogues, not exact matches.
        * Pass: The Agent adopts the Consensus Strategy (e.g., same solvent class, similar temperature range, same catalyst type) found in the Contexts.
        * Fail: The Agent invents conditions that appear in NONE of the Contexts (e.g., Contexts use acidic conditions; Agent uses basic conditions).

    * **Evaluation Task: The Grounding Check**
    Assess the Target Recipe across 4 specific dimensions. For each, determining if the Agent's choice is Supported by Evidence.
        * 1. Solvent Grounding (0-2)
            * 2 (Strong Support): The solvent used is present in at least one of the retrieved contexts OR is a direct equivalent (e.g., Context uses Benzene; Agent uses Toluene).
            * 1 (Weak Support): The solvent class is similar (e.g., both polar aprotic), but the specific choice is not in the context.
            * 0 (Unsupported): The solvent contradicts the context (e.g., Contexts are all aqueous; Agent uses anhydrous THF).
        * 2. Reagent/Catalyst Alignment (0-2)
            * 2 (Aligned): The key reagents (Base, Catalyst, Oxidant) match the type found in the contexts
            * 1 (Partial): Agent misses a catalyst present in the contexts or adds a reagent not seen in the evidence.
            * 0 (Contradiction): Agent uses a reagent chemically incompatible with the retrieved reaction types.
        * 3. Temperature/Time Logic (0-2)
            * 2 (Consistent): The temperature falls within the range of the retrieved contexts.
            * 1 (Deviant but Plausible): Agent suggests a standard temp (e.g., Room Temp) when contexts suggest heating, or vice versa, without clear justification.
            * 0 (Hallucinated): Contexts suggest mild conditions (0 C); Agent suggests extreme heat (200 C).
        * 4. Work-up Consistency (0-2)
            * 2 (Supported): The isolation method (Filtration vs Extraction) matches the majority of the contexts.
            * 1 (Generic): Agent gives generic "work up" instructions while Contexts provided specific quench steps.
            * 0 (Unsupported): Contexts specifically warn to avoid water; Agent suggests aqueous wash.

    * **Output JSON Format**
        {
            "rag_grounding_score": <sum 0-8>,
            "evidence_utilization": {
                "solvent_supported": <bool>,
                "reagent_supported": <bool>,
                "temp_supported": <bool>,
                "workup_supported": <bool>
            },
            "primary_source_index": <int or null>, // 0, 1, or 2. Which retrieval did it resemble most?
            "hallucination_warning": <bool>, // True if Score < 4 (Agent ignored the RAG)
            "reasoning": "The Agent correctly followed the 'Palladium/Toluene' consensus found in Contexts 0 and 1. However, it hallucinated a 'Room Temperature' condition while all retrieved evidence suggested heating to 100C."
        }
    """)

    prompt = prompt_template.substitute(
        retrieval_rerank=retrieval_rerank,
        full_recipe=full_recipe,
        product_smiles=product_smiles,
    )
    await rate_limiter.aacquire()

    
    # LiteLLM Unified Call
    print(f"CURRENT PROMPT: {prompt}")
    # response = await client.chat.completions.create(
    #             model=model_id,
    #             stream=False,
    #             messages=[
    #                 {"role": "system", "content": "You are a robotic, highly critical chemistry auditor."},
    #                 {"role": "user", "content": prompt}
    #             ],
    #             temperature=_TEMPERATURE, # for Gemini with temperature 0, clause temperatue 1 for thinking
    #             reasoning_effort="high", 
    #             response_format={"type": "json_object"}
    #         )

    # full_text = response.choices[0].message.content
    
    # # 1. Access the usage object
    # usage = response.usage
    
    response = await client.responses.create(
    model=model_id,
    input=[
        {"role": "system", "content": "You are a robotic, highly critical chemistry auditor."},
        {"role": "user", "content": prompt}
    ],
    reasoning={
        "effort": "high",
        "summary": "detailed"
        }
    )
    usage = response.usage
    full_text = ""
    thinking_text = ""
    if hasattr(response, "output"):
        completion_tokens = usage.output_tokens
        thinking_tokens = getattr(usage.output_tokens_details, "reasoning", 0)
        print(f"Completion Tokens: {completion_tokens}")
        print(f"Thinking Tokens: {thinking_tokens}")
        for item in response.output:
            if item.type == "message":
                for content_block in item.content:
                    if content_block.type in ("text", "output_text"):
                        full_text += content_block.text
            elif item.type == "reasoning":
                if getattr(item, "summary", None):
                    parts = [getattr(s, "text", "") or str(s) for s in item.summary]
                    thinking_text += "\n\n".join(parts)
                elif getattr(item, "content", None):
                    thinking_text += str(item.content)
    else:
        full_text = response.choices[0].message.content
        thinking_text = getattr(response.choices[0].message, "reasoning_content", "")
  

    # Extract JSON
    try:
        # Regex handles cases where LLM puts text before/after the JSON
        json_str = re.search(r"\{.*\}", full_text, re.DOTALL).group()
        scores = json.loads(json_str)
        # Preserve the CoT for the CSV
        scores['full_chain_of_thought'] = thinking_text
        scores['inputs'] = sample
        scores["idx"] = sample["idx"]
        print("===debug SHAN: score is ", scores)
        return scores
    except Exception as e:
        print(f"Parsing Error: {e}")
        return None

def save_audit_to_csv(data_ls, prefix="gpt-5-pro"):
    if not data_ls: return
    json_file = prefix + ".json"
    csv_file = prefix + ".csv"
    with open(json_file, 'a', encoding='utf-8') as f:
        # indent=4 adds the visual structure
        # ensure_ascii=False keeps chemical SMILES and symbols readable
        json.dump(data_ls, f, indent=4, ensure_ascii=False)
    print(f"✅ Saved visually formatted JSON to {csv_file}")
    #print(f"FINAL DEBUG result is {data_ls}")
    file_exists = os.path.isfile(csv_file)
    # Use the keys from the first valid dictionary
    fieldnames = data_ls[0].keys()
    with open(csv_file, 'a', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        
        # Write header ONLY if the file is brand new
        if not file_exists:
            writer.writeheader()
        
        # 3. FIX SPEED: Write all rows at once
        writer.writerows(data_ls)

